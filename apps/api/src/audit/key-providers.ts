import { createHmac, hkdfSync } from 'node:crypto';
import { DecryptCommand, GenerateDataKeyCommand, type KMSClient } from '@aws-sdk/client-kms';

/** Where a tenant's wrapped data key is kept (the tenant_data_key table). */
export interface DataKeyStore {
  find(tenantId: string): Promise<{ keyRef: string; wrappedKey: Buffer } | null>;
  save(
    tenantId: string,
    key: { provider: 'kms' | 'local'; keyRef: string; wrappedKey: Buffer },
  ): Promise<void>;
}

/** Gives the plaintext 256-bit data key for a tenant, creating it on first use. */
export interface DataKeyProvider {
  dataKey(tenantId: string): Promise<{ keyRef: string; key: Buffer }>;
}

/** AWS KMS: the data key is generated by KMS and stored only wrapped; KMS unwraps it on first use. */
export class KmsDataKeyProvider implements DataKeyProvider {
  private readonly cache = new Map<string, Promise<{ keyRef: string; key: Buffer }>>();

  constructor(
    private readonly kms: Pick<KMSClient, 'send'>,
    private readonly kmsKeyId: string,
    private readonly store: DataKeyStore,
  ) {}

  dataKey(tenantId: string) {
    let entry = this.cache.get(tenantId);
    if (!entry) {
      entry = this.load(tenantId).catch((error: unknown) => {
        this.cache.delete(tenantId);
        throw error;
      });
      this.cache.set(tenantId, entry);
    }
    return entry;
  }

  private async load(tenantId: string) {
    const context = { tenant: tenantId };
    const stored = await this.store.find(tenantId);
    if (stored) {
      const result = await this.kms.send(
        new DecryptCommand({
          CiphertextBlob: stored.wrappedKey,
          KeyId: stored.keyRef,
          EncryptionContext: context,
        }),
      );
      return { keyRef: stored.keyRef, key: Buffer.from(result.Plaintext!) };
    }
    const generated = await this.kms.send(
      new GenerateDataKeyCommand({
        KeyId: this.kmsKeyId,
        KeySpec: 'AES_256',
        EncryptionContext: context,
      }),
    );
    const keyRef = generated.KeyId ?? this.kmsKeyId;
    await this.store.save(tenantId, {
      provider: 'kms',
      keyRef,
      wrappedKey: Buffer.from(generated.CiphertextBlob!),
    });
    return { keyRef, key: Buffer.from(generated.Plaintext!) };
  }
}

/**
 * Development only (refused in production by config): derives each tenant's key from LOCAL_FIELD_KEY,
 * so no KMS is needed locally.
 */
export class LocalDataKeyProvider implements DataKeyProvider {
  private readonly keyRef: string;

  constructor(private readonly masterKey: Buffer) {
    if (masterKey.length !== 32) throw new Error('Local field key must be 32 bytes');
    this.keyRef = `local:${createHmac('sha256', masterKey).update('key-ref').digest('hex').slice(0, 12)}`;
  }

  async dataKey(tenantId: string) {
    // The salt is fixed per tenant so the same key is derived every time.
    const salt = Buffer.from(`ipro-tenant:${tenantId}`);
    const key = Buffer.from(hkdfSync('sha256', this.masterKey, salt, 'ipro-field-key', 32));
    return { keyRef: this.keyRef, key };
  }
}
